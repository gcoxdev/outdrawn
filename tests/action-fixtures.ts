import { createNewGame } from "../src/game/setup";
import { validateSavedGame } from "../src/game/validateSave";
import { saveGame } from "../src/game/persistence";

export function fixtures() {
  let sequence = 0;
  const card = (definitionId: string) => ({ instanceId: `action_${++sequence}`, definitionId });
  const base = createNewGame(["Ari", "Blake", "Casey"], () => 0);
  base.settings.passDeviceMode = false;
  base.players.forEach(player => { player.hand = [card("weapon_pistol"), card("defense_dodge")]; });
  base.players[0].hand.push(card("ability_adrenaline"), card("ability_mark_target"));
  const crowded = structuredClone(base);
  crowded.players[0].hand = Array.from({ length: 30 }, () => card("weapon_pistol"));
  const teams = structuredClone(base);
  teams.players[0].teamId = teams.players[1].teamId = "team_1";
  teams.players[2].teamId = "team_2";
  teams.settings.allowTeamHealing = teams.settings.allowTeamCardTransfer = true;
  teams.players[0].health = teams.settings.maxHealth;
  teams.players[1].health = teams.settings.maxHealth - 4;
  teams.players[0].hand.push(card("healing_bandage"));
  const soloHealing = structuredClone(base);
  soloHealing.players[0].health = 10;
  soloHealing.players[0].hand = ["healing_bandage", "healing_medkit", "healing_painkillers", "healing_field_dressing"].map(card);
  soloHealing.mainDeck = [card("weapon_pistol")];
  const fullHealth = structuredClone(soloHealing);
  fullHealth.players[0].health = fullHealth.settings.maxHealth;
  const lastTeammate = structuredClone(teams);
  lastTeammate.players[0].health = 10;
  lastTeammate.players[1].health = 0;
  lastTeammate.players[1].eliminated = true;
  lastTeammate.discardPile.push(...lastTeammate.players[1].hand);
  lastTeammate.players[1].hand = [];
  const teamHealingDisabled = structuredClone(teams);
  teamHealingDisabled.players[0].health = 10;
  teamHealingDisabled.settings.allowTeamHealing = false;
  const multipleTeammates = createNewGame(["Ari", "Blake", "Casey", "Morgan"], () => 0);
  multipleTeammates.settings.passDeviceMode = false;
  multipleTeammates.players.forEach((player, index) => { player.teamId = index < 3 ? "team_1" : "team_2"; player.hand = [card("weapon_pistol")]; });
  const smoke = structuredClone(base);
  smoke.smokeProtectedPlayerIds = ["player_2", "player_3"];
  smoke.players[0].hand.push(card("weapon_minigun"));
  const intimidate = structuredClone(base);
  intimidate.intimidations = { player_1: ["player_2"] };
  const noCost = structuredClone(intimidate);
  noCost.players[0].hand = [noCost.players[0].hand[0]];
  const exhausted = structuredClone(base);
  exhausted.players[0].actionsRemaining = 0;
  const exhaustedOptions = structuredClone(teams);
  exhaustedOptions.players[0].actionsRemaining = 0;
  exhaustedOptions.players[0].hand.push(card("weapon_minigun"), card("ability_steal"));
  const oneAction = structuredClone(teams);
  oneAction.players[0].actionsRemaining = 1;
  oneAction.players[0].hand.push(card("healing_medkit"));
  const exhaustedReaction = structuredClone(base);
  exhaustedReaction.players[1].actionsRemaining = 0;
  exhaustedReaction.pendingReaction = { attackerId: "player_1", defenderId: "player_2", weapon: exhaustedReaction.players[0].hand[0], baseDamage: 3 };
  const redirect = structuredClone(smoke);
  const decoy = card("defense_ricochet");
  redirect.players[1].hand.push(decoy);
  redirect.pendingRedirect = { attackerId: "player_1", defenderId: "player_2", weapon: redirect.players[0].hand[0], baseDamage: 3, decoy };
  redirect.players[1].actionsRemaining = 0;
  const large = createNewGame(Array.from({ length: 100 }, (_, i) => `Player ${i + 1}`), () => 0);
  large.settings.passDeviceMode = false;
  large.players[0].hand = [card("weapon_pistol")];
  return Object.fromEntries(Object.entries({ base, crowded, teams, soloHealing, fullHealth, lastTeammate, teamHealingDisabled, multipleTeammates, smoke, intimidate, noCost, exhausted, exhaustedOptions, oneAction, exhaustedReaction, redirect, large }).map(([name, state]) => {
    validateSavedGame(state);
    let serialized = "";
    saveGame(state, { setItem: (_key, value) => { serialized = value; }, removeItem() {} });
    return [name, serialized];
  }));
}
